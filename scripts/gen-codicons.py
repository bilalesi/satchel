#!/usr/bin/env python3
"""Generates Sources/Vault/UI/Codicon.swift: a typed enum of the Codicons the app uses.

Source: @vscode/codicons 0.0.46 (CC BY 4.0), font in Resources/Fonts/codicon.ttf,
name→codepoint table in scripts/codicon.csv. Add a name to USED and re-run.
"""
import csv, pathlib, sys

USED = """
account add archive check chevron-down chevron-right circle-slash close cloud-download copy
dashboard database edit error extensions eye eye-closed folder folder-opened github globe
history inbox info key link link-external lock note pass-filled plug pulse radio-tower record
refresh remove save search settings-gear shield sign-out sparkle star-empty star-full sync tag
terminal trash unlock verified-filled warning
git-merge server cloud cloud-upload briefcase home heart bookmark rocket flame law mail comment
device-mobile credit-card gift book beaker organization layers arrow-down arrow-up debug-restart
tools library game mortar-board lightbulb coffee package ellipsis diff-added arrow-right
clippy file-media sign-out question layout-sidebar-left layout-sidebar-left-off
""".split()

root = pathlib.Path(__file__).resolve().parent.parent
table = {row["short_name"]: row["unicode"] for row in csv.DictReader(open(root / "scripts/codicon.csv"))}
missing = [n for n in USED if n not in table]
if missing:
    sys.exit(f"unknown codicons: {missing}")

def case_name(n):
    parts = n.split("-")
    name = parts[0] + "".join(p.capitalize() for p in parts[1:])
    return f"`{name}`" if name in {"repeat", "default", "import", "extension", "protocol"} else name

lines = [
    "// Generated by scripts/gen-codicons.py. Do not edit.",
    "// Codicons by Microsoft, CC BY 4.0 (Resources/Fonts/codicon-LICENSE.txt).",
    "",
    "enum Codicon: UInt32, CaseIterable, Sendable {",
]
for n in sorted(set(USED)):
    lines.append(f"    case {case_name(n)} = 0x{table[n]}")
lines += ["", "    /// The glyph in the `codicon` font.", "    var character: Character { Character(UnicodeScalar(rawValue)!) }", "}", ""]
(root / "Sources/Vault/UI/Codicon.swift").write_text("\n".join(lines))
print(f"wrote {len(USED)} icons")
