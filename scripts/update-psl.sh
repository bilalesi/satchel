#!/bin/zsh
# Regenerates Sources/VaultCore/Browser/PublicSuffixData.swift from publicsuffix.org.
# The list is compiled into the binary on purpose: a SwiftPM resource bundle is looked up
# next to the app and, failing that, at the absolute build path of the machine that built it,
# which does not exist on another Mac. Data in source cannot be missing.
# Source: https://publicsuffix.org/list/public_suffix_list.dat (Mozilla Public License 2.0)
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="Sources/VaultCore/Browser/PublicSuffixData.swift"
TMP="$(mktemp)"
curl -fsSL https://publicsuffix.org/list/public_suffix_list.dat -o "$TMP"
[ "$(wc -l < "$TMP")" -gt 5000 ] || { echo "unexpectedly short list" >&2; exit 1; }
grep -q '"""' "$TMP" && { echo "list contains a triple quote" >&2; exit 1; }
{
  echo "// Generated by scripts/update-psl.sh. Do not edit."
  echo "// Public Suffix List, https://publicsuffix.org, Mozilla Public License 2.0."
  echo "// Fetched $(date -u +%Y-%m-%d). Only rule lines are kept."
  echo
  echo "enum PublicSuffixData {"
  echo '    static let rules = #"""'
  grep -vE '^\s*(//|$)' "$TMP"
  echo '"""#'
  echo "}"
} > "$OUT"
rm -f "$TMP"
echo "wrote $OUT ($(grep -vcE '^\s*(//|$)' "$OUT") lines)"
